import 'cloud_endpoint.dart';

/// Build-time defaults for the optional cloud backend.
///
/// These are **defaults, not the product**: since option D the server is a
/// per-device setting (`cloud_runtime.dart` + `AppSettingsStore`), and a public
/// build may ship with no values at all. When a build does carry them (personal
/// builds, and every install that predates runtime selection), the boot path
/// copies them into the keychain once, so an ordinary update keeps the server.
///
/// The URL and publishable key are safe to ship: access is gated entirely by
/// row-level security in `supabase/migrations`. The `service_role` key must
/// never appear here.
class CloudConfig {
  CloudConfig._();

  static const String url = String.fromEnvironment(
    'SUPABASE_URL',
    defaultValue: '',
  );

  static const String anonKey = String.fromEnvironment(
    'SUPABASE_ANON_KEY',
    defaultValue: '',
  );

  /// Where users go to manage their sources and claim a device's pairing code.
  ///
  /// Still a compile-time constant because installs that predate runtime
  /// selection have nothing else to fall back to; [CloudRuntime.panelUrl]
  /// prefers the configured server's panel. See `redirect/index.html` and
  /// docs/cloud-sync.md before changing it.
  static const String panelUrl = String.fromEnvironment(
    'PANEL_URL',
    defaultValue: 'https://panel.iptvs.click/',
  );

  /// The build's default endpoint, or null when the build ships unconfigured
  /// (the published build's normal state since option D).
  static CloudEndpoint? get defaultEndpoint {
    if (url.isEmpty || anonKey.isEmpty) return null;
    return CloudEndpoint.parse(url: url, anonKey: anonKey, panelUrl: panelUrl);
  }

  /// Whether this build carries a default server at all.
  static bool get hasDefaults => defaultEndpoint != null;
}


/// The panel link the pairing screen turns into a QR code: [panelUrl] carrying
/// the device's [code] as a `code=` query parameter, which the panel reads to
/// prefill its Pair form (`panel/src/validate.js` `pairingCodeFromUrl`).
///
/// The primary device here is a TV: entering eight characters into a phone by
/// reading them off the screen across the room is the slowest step in pairing,
/// and it is the one step the app can hand over to a camera. Scanning lands the
/// user on the panel *and* fills the field.
///
/// Pure so it can be tested, and deliberately conservative:
///
/// - An unparseable [panelUrl] (a bad `PANEL_URL` define) returns it unchanged
///   rather than throwing — the QR is a convenience, and the printed link and
///   the code beside it are the real instructions.
/// - A blank [code] returns the plain panel URL, so a QR rendered while the
///   code is still being requested points somewhere useful instead of
///   advertising an empty parameter.
/// - Any existing query is preserved; only `code` is replaced.
String pairingPanelLink(String panelUrl, String code) {
  final trimmed = code.trim();
  final uri = Uri.tryParse(panelUrl);
  if (uri == null || !uri.hasScheme) return panelUrl;
  if (trimmed.isEmpty) return panelUrl;
  return uri.replace(
    queryParameters: {...uri.queryParameters, 'code': trimmed},
  ).toString();
}

/// The pairing code inside a QR scan, or null when [raw] holds none.
///
/// Accepts what the app itself prints — the panel link from [pairingPanelLink],
/// where the code rides in `?code=` — and a bare code, because a QR generated by
/// hand (a panel URL from an older install, a code pasted into a generic QR
/// tool) is still a code. Codes are eight characters of
/// `ABCDEFGHJKMNPQRSTUVWXYZ23456789` (`gen_pairing_code`), so the result is
/// upper-cased and length-checked rather than trusted: feeding the RPC garbage
/// costs a round trip and reports "invalid or expired code", which reads as the
/// code's fault rather than the scan's.
String? pairingCodeFromScan(String raw) {
  final text = raw.trim();
  if (text.isEmpty) return null;
  final uri = Uri.tryParse(text);
  final fromLink = uri?.queryParameters['code']?.trim() ?? '';
  final candidate = (fromLink.isNotEmpty ? fromLink : text).toUpperCase();
  return _kPairingCodePattern.hasMatch(candidate) ? candidate : null;
}

/// `gen_pairing_code`'s alphabet, eight characters, with an optional dash for a
/// hand-written code. Deliberately no `0/1/I/L/O`: those are the characters the
/// server never issues.
final RegExp _kPairingCodePattern = RegExp(
  r'^[ABCDEFGHJKMNPQRSTUVWXYZ23456789]{4,16}$',
);
